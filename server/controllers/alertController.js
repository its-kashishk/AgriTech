const mongoose = require('mongoose');
const Alert = require('../models/Alert');
const ApiError = require('../utils/ApiError');
const { evaluateUser } = require('../services/alertService');
const { ok } = require('../utils/respond');

const mineFilter = (id) => ({ $or: [{ user: id }, { user: null }] });

exports.list = async (req, res) => {
  await evaluateUser(req.user.id); // refresh rule-based alerts (harvest, soil)
  const items = await Alert.find({ ...mineFilter(req.user.id), ...(req.query.unread === 'true' ? { read: false } : {}) }).sort('-createdAt').limit(50);
  ok(res, items, 200, { meta: { note: 'Alerts with source "rule" are generated by simple documented rules, not by an AI model.' } });
};
exports.markRead = async (req, res) => {
  const a = await Alert.findOneAndUpdate({ _id: req.params.id, user: req.user.id }, { read: true }, { returnDocument: 'after' });
  if (!a) throw new ApiError(404, 'Alert not found (broadcast alerts cannot be marked read)');
  ok(res, a);
};
exports.broadcast = async (req, res) => ok(res, await Alert.create({ ...req.body, source: 'admin', user: null, key: `admin:${new mongoose.Types.ObjectId()}` }), 201, { message: 'Advisory published to all farmers' });
exports.removeBroadcast = async (req, res) => {
  const a = await Alert.findOneAndDelete({ _id: req.params.id, source: 'admin' });
  if (!a) throw new ApiError(404, 'Advisory not found');
  ok(res, { id: a.id }, 200, { message: 'Advisory deleted' });
};
